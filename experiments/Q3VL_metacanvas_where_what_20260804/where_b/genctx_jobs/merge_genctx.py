#!/usr/bin/env python
"""Merge the per-shard ``genwhere/2`` publications into the one root the
consumers read, and prove -- before anything is written -- that the pieces
actually form the split.

Why a re-publish and not a directory shuffle
--------------------------------------------
Every consumer (:class:`q3vl.whereb.stores.GenContextStore`,
:class:`q3vl.what.stores.ColorGenContextStore`) opens *one* root, reads
``manifest.json``, refuses anything whose ``status`` is not ``complete``, and
then reads members positionally out of ``shards/*.tar`` using the offsets in
``indexes/shard-*.idx.jsonl``.  Renaming tars and concatenating indexes by hand
would mean hand-writing a manifest, hand-recomputing the per-shard digests and
hand-rebuilding the SQLite catalog -- i.e. reimplementing the publisher, badly.
Streaming the records back through the producer's own
:func:`q3vl.whereb.gencontext.publish_generated` keeps the canonical format,
the canonical ``producer`` / ``source_label`` strings, the atomic staging
rename, and the catalog-vs-JSONL verification, for free.  It costs one pass over
~160k records of ~1-3 KB (minutes, CPU only, no GPU).

What is checked (all of it *before* the merged root is published)
-----------------------------------------------------------------
1. every shard root exists, its manifest says ``complete``, and its index is
   readable;
2. the shards' ``sample_id`` sets are **exactly** the planned partition of the
   split -- not merely disjoint and covering.  This is what catches a shard that
   was run with the wrong ``--shard`` / ``--num-shards`` / ``--shard-mode``, a
   mistake that a "union covers the split" test cannot see when two such
   mistakes cancel out;
3. the split's own sample set (via the sanctioned ``open_dataset``, so the same
   build filter the producer used) is covered exactly: no missing, no extra;
4. every record carries the v2 schema, the expected ``mode``, and **the same
   checkpoint** -- half a split generated by checkpoint-2488 and half by
   checkpoint-4976 would be invisible in the loss and would silently break the
   "generated context comes from the frozen SFT model" premise.

Then, and only then, the merged root is published and re-opened, and the merged
summary (format-failure / truncation / stop-reason / length stats, both
segments) is written to the delivery report.

Consumer-path compatibility (finding CX-1, see NOTES.md)
--------------------------------------------------------
The two consumers disagree about where a published generation lives:

* Where-B: ``GENCTX_DIR/<split>``            (``run_where_b.py``, hard-coded)
* Stage-What: ``<root>/<split>/<mode>``      (``run_what.py`` / ``evaluate_what.py``)

so ``genwhere/train`` has to be *both* a published dataset root and a directory
of per-mode roots.  ``--compat-symlinks`` (default on) makes both true without
touching either package: ``genwhere/<split>/two_segment -> ../<split>`` and
``genwhere/<split>/forced_color -> ../<split>-forced_color``.  Readers only ever
look at ``manifest.json`` / ``indexes/`` / ``shards/``, so the extra entries are
inert.  ``--no-compat-symlinks`` leaves the layout alone.

Usage:
    python merge_genctx.py --split train --mode two_segment \\
        --shard-root /mnt/nfs/.../genwhere/_shards/two_segment/train --num-shards 8
"""

from __future__ import annotations

import sqlite3  # noqa: F401  (R6: before torch, this is an entry point)

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Any, Iterator

sys.path.insert(0, str(Path(__file__).resolve().parent))
# see genctx_shard.py: a script run by absolute path does not get the repo on
# sys.path, whatever the cwd is
_REPO = Path(__file__).resolve().parents[4]
if (_REPO / "q3vl").is_dir() and str(_REPO) not in sys.path:
    sys.path.insert(0, str(_REPO))
from genctx_shard import shard_indices, shard_tag  # noqa: E402


def _git_commit(repo: Path) -> str | None:
    try:
        out = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"],
                             capture_output=True, text=True, timeout=20)
        return out.stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        return None


def leaf_of(split: str, mode: str) -> str:
    """The directory name the producer uses for ``(split, mode)``."""
    return split if mode == "two_segment" else f"{split}-{mode}"


def _iter_verified(stores, expected_mode: str, schema: str,
                   checkpoints: set[str], counters: dict[str, int]
                   ) -> Iterator[dict[str, Any]]:
    """Yield records while asserting the per-record contract.

    Raw records, not payloads: ``publish_generated`` applies
    ``genwhere_payload`` itself.
    """
    for tag, store in stores:
        for rec in store.iter_records():
            sid = rec.get("sample_id")
            if rec.get("schema_version") != schema:
                raise SystemExit(
                    f"{tag}/{sid}: schema {rec.get('schema_version')!r} != {schema!r}")
            if rec.get("mode") != expected_mode:
                raise SystemExit(
                    f"{tag}/{sid}: mode {rec.get('mode')!r} != {expected_mode!r}")
            ck = str(rec.get("checkpoint"))
            checkpoints.add(ck)
            if len(checkpoints) > 1:
                raise SystemExit(
                    f"{tag}/{sid}: records come from more than one checkpoint "
                    f"{sorted(checkpoints)}; a split generated half by one model "
                    "and half by another is not a usable context cache")
            counters["n"] += 1
            counters["format_failure"] += int(bool(rec.get("format_failure")))
            counters["color_format_failure"] += int(bool(rec.get("color_format_failure")))
            yield rec


def _await_read_mirror(out_root: Path, manifest: dict[str, Any],
                       timeout_s: float = 300.0, poll_s: float = 5.0) -> None:
    """Block until every published shard is visible through the read mirror.

    ``os.stat`` only, on the soft (nfs3) mount, so this can neither hang nor
    write.  Raises rather than proceeding: a read-back that silently skipped the
    verification would be the "second failure mode" of the campaign's cache
    contract -- quiet, and indistinguishable from success.
    """
    from q3vl.train.shards import rewrite_read_path

    wanted = [out_root / "manifest.json"] + [
        out_root / s["tar"] for s in manifest.get("shards", [])]
    t0 = time.time()
    while True:
        missing = [p for p in wanted if not Path(rewrite_read_path(p)).exists()]
        if not missing:
            print(json.dumps({"read_mirror_visible": len(wanted),
                              "waited_s": round(time.time() - t0, 1)}), flush=True)
            return
        if time.time() - t0 > timeout_s:
            raise SystemExit(
                f"{len(missing)} published file(s) are still invisible through "
                f"the read mirror after {timeout_s:.0f}s, e.g. "
                f"{rewrite_read_path(missing[0])}.  The publication itself is "
                f"complete at {out_root}; move it aside and re-run the merge.")
        print(json.dumps({"waiting_for_read_mirror": len(missing),
                          "elapsed_s": round(time.time() - t0, 1)}), flush=True)
        time.sleep(poll_s)


def main() -> int:
    from q3vl.whereb.config import GENCTX_DIR, GENCTX_MODES, REPORT_DIR, SCHEMA_GENCTX

    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--split", required=True)
    ap.add_argument("--mode", default="two_segment", choices=list(GENCTX_MODES))
    ap.add_argument("--shard-root", required=True,
                    help="parent holding shard<i>of<n>/<leaf> (what genctx_shard.py "
                         "was given as --out-root)")
    ap.add_argument("--num-shards", type=int, required=True)
    ap.add_argument("--shard-mode", default="interleave",
                    choices=("interleave", "contiguous"))
    ap.add_argument("--out", default=None,
                    help="merged root; default GENCTX_DIR/<leaf>")
    ap.add_argument("--report", default=None,
                    help="merge report; default <REPORT_DIR>/genctx_<leaf>.json")
    ap.add_argument("--force-report", action="store_true",
                    help="overwrite an existing report after backing it up as "
                         ".superseded (Stage-What R5 rule: never silently)")
    ap.add_argument("--compat-symlinks", dest="compat", action="store_true", default=True)
    ap.add_argument("--no-compat-symlinks", dest="compat", action="store_false")
    ap.add_argument("--no-verify-sha", dest="verify", action="store_false", default=True,
                    help="skip per-member sha256 on read (not recommended)")
    ap.add_argument("--check-only", action="store_true",
                    help="run every pre-publication check and stop")
    args = ap.parse_args()

    from q3vl.whereb.data import open_dataset
    from q3vl.whereb.gencontext import publish_generated, summarise_records
    from q3vl.whereb.stores import GenContextStore

    leaf = leaf_of(args.split, args.mode)
    out_root = Path(args.out) if args.out else Path(GENCTX_DIR) / leaf
    report_path = Path(args.report) if args.report else Path(REPORT_DIR) / f"genctx_{leaf}.json"
    t0 = time.time()

    if out_root.exists() or out_root.is_symlink():
        raise SystemExit(
            f"{out_root} already exists. Publication is atomic; move the old "
            "directory aside (do NOT delete it) before merging again.")

    # -- 1. the split's own expectation, through the sanctioned factory -------
    ds, ds_info = open_dataset(args.split, need_mask=False)
    all_ids = [r.sample_id for r in ds.refs]
    n_all = len(all_ids)
    print(json.dumps({"split": args.split, "mode": args.mode, "leaf": leaf,
                      "n_samples_expected": n_all, "dataset": ds_info}), flush=True)

    # -- 2. every shard: exists, complete, and is exactly its planned slice ---
    stores: list[tuple[str, Any]] = []
    shard_facts: list[dict[str, Any]] = []
    seen: set[str] = set()
    for i in range(args.num_shards):
        tag = shard_tag(i, args.num_shards)
        root = Path(args.shard_root) / tag / leaf
        store = GenContextStore(root, verify=args.verify)     # raises if incomplete
        got = {sid for sid, suf in store.rows if suf == store.SUFFIX}
        want = {all_ids[j] for j in shard_indices(n_all, i, args.num_shards,
                                                  args.shard_mode)}
        if got != want:
            raise SystemExit(
                f"{tag}: sample set != the planned {args.shard_mode} slice "
                f"(have {len(got)}, planned {len(want)}, "
                f"missing {len(want - got)}, unexpected {len(got - want)}; "
                f"e.g. missing={sorted(want - got)[:3]} extra={sorted(got - want)[:3]}). "
                "Re-check --shard / --num-shards / --shard-mode of that job.")
        if seen & got:
            raise SystemExit(f"{tag}: {len(seen & got)} sample_ids already in an earlier shard")
        seen |= got
        stores.append((tag, store))
        shard_facts.append({"tag": tag, "root": str(root), **store.facts()})
        print(json.dumps({"shard_ok": tag, "n": len(got)}), flush=True)

    missing = [s for s in all_ids if s not in seen]
    extra = sorted(seen - set(all_ids))
    if missing or extra:
        raise SystemExit(
            f"coverage is not exact: {len(missing)} missing (e.g. {missing[:3]}), "
            f"{len(extra)} unexpected (e.g. {extra[:3]})")

    if args.check_only:
        print(json.dumps({"check_only": True, "shards": len(stores),
                          "n_samples": len(seen), "seconds": round(time.time() - t0, 1)},
                         indent=2), flush=True)
        return 0

    # -- 3. publish (atomic) --------------------------------------------------
    checkpoints: set[str] = set()
    counters = {"n": 0, "format_failure": 0, "color_format_failure": 0}
    manifest = publish_generated(
        _iter_verified(stores, args.mode, SCHEMA_GENCTX, checkpoints, counters),
        out_root, args.split)
    if counters["n"] != n_all:
        raise SystemExit(
            f"published {counters['n']} records but the split has {n_all}; "
            f"{out_root} must be moved aside and the merge repeated")

    # -- 3b. wait for the soft READ mirror to see what we just wrote ----------
    # We publish through the rw mount (nfs4.1) but every consumer -- and step 4
    # below, via ShardStore's `resolve_read_path` -- reads through /mnt/nfs-ro
    # (nfs3, soft).  A directory created seconds ago is not in that client's
    # dentry cache yet, so the read-back raced and failed with ENOENT on
    # `shards/shard-00000.tar` (observed 2026-08-10, forced_color/V_what).  The
    # entry becomes visible within acdirmax (60 s by default), so this waits for
    # it rather than skipping the verification or reading through the hard mount.
    _await_read_mirror(out_root, manifest)

    # -- 4. read the merged root back through the consumer's own class --------
    merged = GenContextStore(out_root, verify=args.verify)
    merged_ids = {sid for sid, suf in merged.rows if suf == merged.SUFFIX}
    if merged_ids != set(all_ids):
        raise SystemExit(f"merged root does not read back as the split "
                         f"({len(merged_ids)} vs {n_all})")
    summary = summarise_records(list(merged.iter_records()))

    # -- 5. compat symlinks ---------------------------------------------------
    links: list[dict[str, Any]] = []
    if args.compat:
        # next to what we just published, NOT the configured production root:
        # a merge into a scratch --out must never reach into /mnt/nfs
        base = out_root.parent
        wanted = [(base / args.split / "two_segment", Path("..") / args.split),
                  (base / args.split / "forced_color", Path("..") / f"{args.split}-forced_color")]
        for link, target in wanted:
            resolved = (link.parent / target)
            row = {"link": str(link), "target": str(target), "status": None}
            if not link.parent.is_dir():
                row["status"] = "skipped_parent_missing"
            elif link.is_symlink() or link.exists():
                row["status"] = ("ok_already" if os.path.realpath(link) == os.path.realpath(resolved)
                                 else "left_alone_points_elsewhere")
            elif not resolved.exists():
                row["status"] = "skipped_target_missing"
            else:
                link.symlink_to(target, target_is_directory=True)
                row["status"] = "created"
            links.append(row)
            print(json.dumps({"compat_symlink": row}), flush=True)

    # -- 6. report ------------------------------------------------------------
    report = {
        "kind": "genctx_merge",
        "split": args.split, "mode": args.mode, "leaf": leaf,
        "out_root": str(out_root),
        "checkpoint": sorted(checkpoints)[0] if checkpoints else None,
        "schema_version": SCHEMA_GENCTX,
        "num_shards": args.num_shards, "shard_mode": args.shard_mode,
        "shard_root": str(args.shard_root),
        "shards": shard_facts,
        "n_samples": counters["n"],
        "n_samples_expected": n_all,
        "coverage": 1.0,
        "manifest": {k: manifest.get(k) for k in
                     ("status", "member_count", "sample_count", "shard_count",
                      "payload_bytes", "dataset_id", "created_at")},
        "store": merged.facts(),
        "summary": summary,
        "compat_symlinks": links,
        "merge_seconds": round(time.time() - t0, 1),
        "git_commit": _git_commit(Path(__file__).resolve().parents[4]),
        "merged_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
    }
    report_path.parent.mkdir(parents=True, exist_ok=True)
    if report_path.exists():
        if not args.force_report:
            alt = report_path.with_suffix(".merged.json")
            print(f"WARNING {report_path} exists; writing {alt} instead "
                  "(--force-report to replace it, with a .superseded backup)",
                  flush=True)
            report_path = alt
        else:
            shutil.copy2(report_path, str(report_path) + ".superseded")
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False),
                           encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if k != "shards"},
                     indent=2, ensure_ascii=False), flush=True)
    print(f"MERGE-OK {leaf} -> {out_root}  report={report_path}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
